// Writes migrations/0001_auth.sql: Better Auth's tables as plain SQL for D1. Better Auth's own migrator cannot run on D1
// (Kysely's SQLite introspection uses PRAGMA, which D1 forbids), so it compiles the schema against an empty in-memory database here.
import { DatabaseSync } from 'node:sqlite'
import { readFileSync, writeFileSync } from 'node:fs'
import { getMigrations } from 'better-auth/db/migration'
import { authOptions } from '../src/auth.js'

const env = { BASE_URL: 'http://localhost', AUTH_SECRET: 'schema-only-schema-only-schema-only-12', ALLOWED_ORIGINS: '', FAKE_OAUTH_URL: 'http://localhost' }
const options = { ...authOptions(env), database: new DatabaseSync(':memory:') }
const { compileMigrations } = await getMigrations(options)
const sql = await compileMigrations()
writeFileSync(new URL('../migrations/0001_auth.sql', import.meta.url), '-- Generated by scripts/gen-auth-schema.mjs (Better Auth ' + JSON.parse(readFileSync(new URL('../node_modules/better-auth/package.json', import.meta.url), 'utf8')).version + '). Do not edit by hand.\n' + sql + '\n')
console.log(sql.split('\n').length + ' lines')
